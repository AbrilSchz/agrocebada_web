import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const scope={window:{}};
vm.runInNewContext(readFileSync(new URL('../public/labels.js',import.meta.url),'utf8'),scope);
const P=scope.window.PRESENTATION;
vm.runInNewContext(readFileSync(new URL('../public/config.js',import.meta.url),'utf8'),scope);
assert.equal(scope.window.CONFIG.baseInicial,'sat');
assert.equal(scope.window.CONFIG.capaInicial,'final_Elevacion_INEGI_CEM4_120m_mean');
assert.equal(P.variable('PREC_2025_05_mean'),'Precipitación · mayo 2025');
assert.equal(P.variable('vegetacion__pro__ndvi__mediana'),'NDVI (Pro) · mediana estacional');
assert.equal(P.variable('fenologia__PRO_ndvi__mes_maximo'),'NDVI (Pro) · mes del máximo');
assert.equal(P.variable('AREA_HA'),'Superficie de la parcela');
assert.equal(P.date('2025-04-01'),'abril 2025');
assert.equal(P.date(''),'Estático');
assert.equal(P.hasNumber(0),true);
assert.equal(P.hasNumber(null),false);
assert.equal(P.hasNumber(''),false);
assert.equal(P.hasNumber(NaN),false);
const prediction={resultado:{prediccion:3.5,observado:null},metricas:{error_firmado_t_ha:null},contribuciones:[],contexto_modelo:{shap_hgb_parcial:[{aporte_redondeado_t_ha:0}]}};
assert.equal(P.capabilities(prediction).errores,false);
assert.equal(P.capabilities(prediction).aportes,true);
const reference={resultado:{prediccion:3.5,observado:3.5},metricas:{error_firmado_t_ha:0},contribuciones:[]};
assert.equal(P.capabilities(reference).errores,true);
assert.equal(P.capabilities(reference).aportes,false);
assert.equal(P.capabilities({}).rendimiento,false);
assert.equal(P.capabilities({}).modelo,false);
console.log('Presentación OK: etiquetas, periodos, ausencia frente a cero y controles según los datos.');
